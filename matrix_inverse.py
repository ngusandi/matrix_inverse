"""Report 1: Matrix inverse via determinant (cofactor) and Gauss-Jordan elimination."""

EPS = 1e-9


# ---------- 1. Matrix input ----------
def input_matrix():
    n = int(input("정방행렬의 차수를 입력하세요: "))
    matrix = []
    for i in range(n):
        row = list(map(float, input(f"{i + 1}행: ").split()))
        if len(row) != n:
            raise ValueError(f"{n}개의 값을 입력해야 합니다.")
        matrix.append(row)
    return matrix


# ---------- 2. Inverse using determinant ----------
def minor(m, i, j):
    """Matrix with row i and column j removed."""
    return [row[:j] + row[j + 1:] for k, row in enumerate(m) if k != i]


def determinant(m):
    n = len(m)
    if n == 1:
        return m[0][0]
    if n == 2:
        return m[0][0] * m[1][1] - m[0][1] * m[1][0]
    # cofactor expansion along the first row
    return sum(((-1) ** j) * m[0][j] * determinant(minor(m, 0, j)) for j in range(n))


def inverse_by_determinant(m):
    n = len(m)
    det = determinant(m)
    if abs(det) < EPS:
        raise ValueError("행렬식이 0이므로 역행렬이 존재하지 않습니다.")
    if n == 1:
        return [[1 / det]]
    # cofactor matrix -> transpose (adjugate) -> divide by det
    cof = [[((-1) ** (i + j)) * determinant(minor(m, i, j)) for j in range(n)]
           for i in range(n)]
    adj = [[cof[j][i] for j in range(n)] for i in range(n)]
    return [[adj[i][j] / det for j in range(n)] for i in range(n)]


# ---------- 3. Inverse using Gauss-Jordan elimination ----------
def inverse_gauss_jordan(m):
    n = len(m)
    # augmented matrix [A | I]
    aug = [m[i][:] + [1.0 if i == j else 0.0 for j in range(n)] for i in range(n)]

    for col in range(n):
        # partial pivoting: pick the row with the largest value in this column
        pivot = max(range(col, n), key=lambda r: abs(aug[r][col]))
        if abs(aug[pivot][col]) < EPS:
            raise ValueError("피벗이 0이므로 역행렬이 존재하지 않습니다.")
        aug[col], aug[pivot] = aug[pivot], aug[col]

        # scale pivot row so the pivot becomes 1
        p = aug[col][col]
        aug[col] = [x / p for x in aug[col]]

        # eliminate this column from every other row
        for r in range(n):
            if r != col:
                factor = aug[r][col]
                aug[r] = [a - factor * b for a, b in zip(aug[r], aug[col])]

    return [row[n:] for row in aug]


# ---------- 4. Output and comparison ----------
def print_matrix(m):
    for row in m:
        print("  ".join(f"{x:9.4f}" for x in row))


def same(a, b):
    return all(abs(x - y) < 1e-6 for ra, rb in zip(a, b) for x, y in zip(ra, rb))


# ---------- Extra feature: verify A x A^-1 = I ----------
def multiply(a, b):
    n = len(a)
    return [[sum(a[i][k] * b[k][j] for k in range(n)) for j in range(n)] for i in range(n)]


def is_identity(m):
    n = len(m)
    return all(abs(m[i][j] - (1 if i == j else 0)) < 1e-6 for i in range(n) for j in range(n))


def main():
    A = input_matrix()

    try:
        inv_det = inverse_by_determinant(A)
        print("\n행렬식으로 구한 역행렬:")
        print_matrix(inv_det)
    except ValueError as e:
        print("\n[행렬식 방법 오류]", e)
        inv_det = None

    try:
        inv_gj = inverse_gauss_jordan(A)
        print("\n가우스-조던 소거법으로 구한 역행렬:")
        print_matrix(inv_gj)
    except ValueError as e:
        print("\n[가우스-조던 방법 오류]", e)
        inv_gj = None

    if inv_det and inv_gj:
        print("\n두 방법의 결과가 동일합니다." if same(inv_det, inv_gj)
              else "\n두 방법의 결과가 다릅니다.")
        print("검증 (A x A^-1 = I):", "성공" if is_identity(multiply(A, inv_gj)) else "실패")


if __name__ == "__main__":
    main()